//! 0.54.0 step 3 Part 7a: generate the two AUR PKGBUILDs (`prikk`, built from the signed source
//! tag, and `prikk-bin`, the published binary) for a release, the same way `installer.rs` already
//! generates `install.sh`/`install.ps1` -- from a `.txt` template, with one placeholder family
//! substituted, written transiently into a release's own `dist/` directory and never committed
//! under the package's real file name.
//!
//! **Why `.txt`, not a literally-named `PKGBUILD`.** A PKGBUILD is itself a bash script -- it is
//! `source`d by `makepkg`, with real shell functions (`prepare()`/`build()`/`package()`) and, for
//! `prikk-bin`, architecture-suffixed array variables (`source_x86_64`, `sha256sums_aarch64`).
//! `installer.rs`'s own doc comment explains in detail why real control-flow-bearing shell text in
//! this repository cannot be a tracked `.sh` file: `reference.rs`'s `scannable_reference_file`
//! treats every `.sh`/`.yml`/`.yaml`/`.md` file anywhere in the tree as a governed procedure and
//! scans it in `command_scan`'s strict mode, which has no concept of shell keywords
//! (`if`/`case`/`for`/`while`) or function bodies -- confirmed against `scannable_reference_file`
//! directly (`reference.rs`, the `matches!` arm listing `"md" | "yml" | "yaml" | "sh"`), not
//! assumed. The same reasoning applies here without needing a literal-`PKGBUILD`-name test: a file
//! named exactly `PKGBUILD` or exactly `.SRCINFO` has no extension at all, so it would never match
//! that `matches!` arm either way -- but a committed, literally-named `PKGBUILD` is still templated
//! bash, still only ever meant to be generated, and keeping it at a `.txt`-suffixed path beside
//! `install.sh.txt`/`install.ps1.txt` keeps one naming convention for "generated text that is not
//! meant to be read as this repository's own shell/YAML/Markdown" rather than two.
//!
//! **`.SRCINFO` is not generated by this module at all.** It is `makepkg --printsrcinfo`'s own
//! output, produced by the `aur-build` CI job after this module writes the `PKGBUILD` -- generating
//! it here would mean re-implementing `makepkg`'s own `.SRCINFO` serialization and risking it
//! drifting from what `makepkg` itself would have written.
//!
//! **The checksums are read, not computed.** `prikk-bin`'s `sha256sums_x86_64`/`sha256sums_aarch64`
//! come from the already-published `<asset>.sha256` files in `dist_dir` -- the same
//! `<hash>  <filename>` shape every other checksum consumer in this project already reads
//! (`release.yml`'s own `sha256sum`/`shasum -a 256` steps produce it). This module never hashes the
//! asset itself: if the checksum file in `dist_dir` is wrong, the AUR package is wrong in exactly
//! the way the release's own published checksum is wrong, which is the release's problem, not an
//! independent one this module introduces.

use std::fs;
use std::path::Path;

use crate::error::{Error, Result};

const PRIKK_TEMPLATE: &str = include_str!("../templates/prikk.PKGBUILD.txt");
const PRIKK_BIN_TEMPLATE: &str = include_str!("../templates/prikk-bin.PKGBUILD.txt");

/// RFC 169 §3.1's fingerprint, pinned by this module's own test against
/// [`crate::release_notes::RELEASE_KEY_FINGERPRINT`] rather than retyped and left to drift --
/// `prikk.PKGBUILD.txt`'s `validpgpkeys` entry carries the literal value (templates are plain text,
/// not Rust, so they cannot reference the constant directly), and the test is what keeps the two in
/// sync.
#[cfg(test)]
pub(crate) const PKGBUILD_FINGERPRINT: &str = "25757DA6CBF7022C4E14CCAC1B3066B87DB99A34";

/// Write `aur/prikk/PKGBUILD` and `aur/prikk-bin/PKGBUILD` under `dist_dir`, for release `tag`.
/// `prikk-bin`'s checksums are read from `dist_dir`'s own already-written
/// `prikk-<target>.tar.gz.sha256` files -- both must already exist, or this fails rather than
/// publishing a package with a placeholder checksum.
pub(crate) fn generate(tag: &str, dist_dir: &Path) -> Result<()> {
    let x86_64 = read_checksum(dist_dir, "prikk-x86_64-unknown-linux-gnu.tar.gz.sha256")?;
    let aarch64 = read_checksum(dist_dir, "prikk-aarch64-unknown-linux-gnu.tar.gz.sha256")?;

    let aur_dir = dist_dir.join("aur");
    write_pkgbuild(
        &aur_dir.join("prikk"),
        &PRIKK_TEMPLATE.replace("PKGVER", tag),
    )?;
    write_pkgbuild(
        &aur_dir.join("prikk-bin"),
        &PRIKK_BIN_TEMPLATE
            .replace("PKGVER", tag)
            .replace("SHA256_X86_64", &x86_64)
            .replace("SHA256_AARCH64", &aarch64),
    )?;
    Ok(())
}

fn write_pkgbuild(package_dir: &Path, content: &str) -> Result<()> {
    fs::create_dir_all(package_dir)?;
    fs::write(package_dir.join("PKGBUILD"), content)?;
    Ok(())
}

/// Reads the hex digest out of a `sha256sum`/`shasum -a 256`-shaped checksum file:
/// `<hash>  <filename>`, hash first, whitespace-delimited -- the same shape `release_notes.rs`'s
/// own `verify_artifact_present` already requires to exist beside every `.build-info.txt` it
/// reads, though that module checks presence only; this one reads the content.
fn read_checksum(dist_dir: &Path, file_name: &str) -> Result<String> {
    let path = dist_dir.join(file_name);
    let content = fs::read_to_string(&path).map_err(|error| {
        Error::new(format!(
            "{}: {error} -- cannot build the AUR prikk-bin PKGBUILD without it",
            path.display()
        ))
    })?;
    let hash = content
        .split_whitespace()
        .next()
        .ok_or_else(|| Error::new(format!("{}: empty checksum file", path.display())))?;
    Ok(hash.to_owned())
}

