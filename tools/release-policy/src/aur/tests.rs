#![allow(clippy::unwrap_used, clippy::expect_used)]

use std::fs;

use super::{PKGBUILD_FINGERPRINT, generate, read_checksum};
use crate::release_notes::RELEASE_KEY_FINGERPRINT;

const TAG: &str = "0.53.0";
const X86_64_SHA256: &str = "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa";
const AARCH64_SHA256: &str = "bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb";

/// Pins the generated `prikk` PKGBUILD text for a fixed version -- any future template edit
/// shows up as an obvious diff in this test's own expected string, not a silent behavior change,
/// the same pattern `installer.rs`'s own tests use for `install.sh`/`install.ps1`.
#[test]
fn generates_the_pinned_prikk_pkgbuild() {
    let temporary = tempfile::tempdir().unwrap();
    let dist = temporary.path();
    write_checksum_files(dist);

    generate(TAG, dist).unwrap();

    let generated = fs::read_to_string(dist.join("aur/prikk/PKGBUILD")).unwrap();
    assert_eq!(
        generated,
        r#"# Maintainer: prikk release workflow <https://github.com/prikk-vcs/prikk>
#
# Generated by `prikk-release-policy generate-aur` at release time and pushed to
# ssh://aur@aur.archlinux.org/prikk.git by the release workflow's aur-push job (0.54.0 step 3
# Part 7) -- never hand-edited, and never committed to this repository under its real `PKGBUILD`
# name. A PKGBUILD is itself a bash script, sourced by `makepkg`, so it gets the same treatment
# installer.rs's own doc comment explains for install.sh: the actual text lives at a `.txt`-suffixed
# path outside command_scan's strict per-command scan, and is only ever written out into a
# transient build directory, never tracked.
#
# sha256sums=('SKIP') is the correct pairing here, not a shortcut: this source is verified by PGP
# signature (validpgpkeys below, plus the `?signed` suffix on the git source), not by content hash.
# makepkg cannot know the tagged commit's hash in advance the way it knows a fixed tarball's, and
# PKGBUILD(5) ("Using VCS Sources") documents SKIP as the correct sha256sums entry for a signature-
# verified VCS source.
pkgname=prikk
pkgver=0.53.0
pkgrel=1
pkgdesc="A version control system, built from the signed source tag"
arch=('x86_64' 'aarch64')
url="https://github.com/prikk-vcs/prikk"
license=('Apache-2.0')
makedepends=('git' 'rust' 'cargo')
source=("git+https://github.com/prikk-vcs/prikk.git#tag=${pkgver}?signed")
sha256sums=('SKIP')
validpgpkeys=('25757DA6CBF7022C4E14CCAC1B3066B87DB99A34')

prepare() {
  cd "$pkgname"
  cargo fetch --locked
}

build() {
  cd "$pkgname"
  cargo build --release --frozen -p prikk
}

package() {
  cd "$pkgname"
  install -Dm755 target/release/prikk "$pkgdir/usr/bin/prikk"
  install -Dm644 LICENSE "$pkgdir/usr/share/licenses/prikk/LICENSE"
}
"#
    );
}

/// Same pinning, for `prikk-bin`, whose text also carries the two checksums read out of
/// `dist_dir`'s own `.sha256` files.
#[test]
fn generates_the_pinned_prikk_bin_pkgbuild() {
    let temporary = tempfile::tempdir().unwrap();
    let dist = temporary.path();
    write_checksum_files(dist);

    generate(TAG, dist).unwrap();

    let generated = fs::read_to_string(dist.join("aur/prikk-bin/PKGBUILD")).unwrap();
    assert_eq!(
        generated,
        r#"# Maintainer: prikk release workflow <https://github.com/prikk-vcs/prikk>
#
# Generated by `prikk-release-policy generate-aur` at release time, the same way and for the same
# reason as prikk's own PKGBUILD (see that template's header, and tools/release-policy/src/aur.rs).
#
# A passing checksum here proves this download matches what the release page published; it does
# not prove *who* published it -- the release assets are not signed, only the tag is (see prikk's
# own PKGBUILD, docs/src/guide/install.md's "Verify the tag" section, and install.sh.txt's own
# header, which state the same limit for every checksum this project publishes).
pkgname=prikk-bin
pkgver=0.53.0
pkgrel=1
pkgdesc="A version control system, prebuilt binary (checksum proves download integrity, not provenance)"
arch=('x86_64' 'aarch64')
url="https://github.com/prikk-vcs/prikk"
license=('Apache-2.0')
provides=('prikk')
conflicts=('prikk')
source_x86_64=("https://github.com/prikk-vcs/prikk/releases/download/${pkgver}/prikk-x86_64-unknown-linux-gnu.tar.gz")
source_aarch64=("https://github.com/prikk-vcs/prikk/releases/download/${pkgver}/prikk-aarch64-unknown-linux-gnu.tar.gz")
sha256sums_x86_64=('aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa')
sha256sums_aarch64=('bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb')

package() {
  install -Dm755 prikk "$pkgdir/usr/bin/prikk"
  install -Dm644 LICENSE "$pkgdir/usr/share/licenses/prikk/LICENSE"
}
"#
    );
}

/// `prikk.PKGBUILD.txt`'s `validpgpkeys` entry is a literal value a plain-text template cannot
/// reference `RELEASE_KEY_FINGERPRINT` by -- this test is what keeps the two from drifting apart,
/// the same role the module doc comment describes for `PKGBUILD_FINGERPRINT`.
#[test]
fn the_pkgbuild_fingerprint_matches_the_shared_release_key_fingerprint() {
    assert_eq!(PKGBUILD_FINGERPRINT, RELEASE_KEY_FINGERPRINT);
}

#[test]
fn generate_fails_without_the_x86_64_checksum_file() {
    let temporary = tempfile::tempdir().unwrap();
    let dist = temporary.path();
    fs::write(
        dist.join("prikk-aarch64-unknown-linux-gnu.tar.gz.sha256"),
        format!("{AARCH64_SHA256}  prikk-aarch64-unknown-linux-gnu.tar.gz\n"),
    )
    .unwrap();

    let error = generate(TAG, dist).expect_err("x86_64 checksum file is missing");
    assert!(
        error
            .to_string()
            .contains("prikk-x86_64-unknown-linux-gnu.tar.gz.sha256"),
        "{error}"
    );
}

#[test]
fn read_checksum_reads_the_hash_before_the_first_whitespace() {
    let temporary = tempfile::tempdir().unwrap();
    fs::write(
        temporary.path().join("sample.sha256"),
        "deadbeef  sample.tar.gz\n",
    )
    .unwrap();

    assert_eq!(
        read_checksum(temporary.path(), "sample.sha256").unwrap(),
        "deadbeef"
    );
}

fn write_checksum_files(dist: &std::path::Path) {
    fs::write(
        dist.join("prikk-x86_64-unknown-linux-gnu.tar.gz.sha256"),
        format!("{X86_64_SHA256}  prikk-x86_64-unknown-linux-gnu.tar.gz\n"),
    )
    .unwrap();
    fs::write(
        dist.join("prikk-aarch64-unknown-linux-gnu.tar.gz.sha256"),
        format!("{AARCH64_SHA256}  prikk-aarch64-unknown-linux-gnu.tar.gz\n"),
    )
    .unwrap();
}
